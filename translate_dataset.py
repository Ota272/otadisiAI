def main():
    print("📂 Загрузка data_cleaned.csv...")
    df = pd.read_csv("data/data_cleaned.csv")
    print(f"   Строк: {len(df):,}")

    # ── Создаём kz версию ──
    print("🔄 Перевод текстовых колонок → kz...")
    df_kz = df.replace(REPLACE_MAP)

    # Добавляем метку языка
    df["language"] = "ru"
    df_kz["language"] = "kz"

    # ── Сохраняем kz версию ──
    kz_path = "data/data_cleaned_kz.csv"
    print(f"💾 Сохранение {kz_path}...")
    df_kz.to_csv(kz_path, index=False, encoding="utf-8-sig")
    print(f"   ✅ {len(df_kz):,} строк")

    # ── Объединяем ru + kz ──
    print("🔗 Объединение ru + kz...")
    df_combined = pd.concat([df, df_kz], ignore_index=True)
    df_combined = df_combined.sample(frac=1, random_state=42).reset_index(drop=True)

    combined_path = "data/data_combined.csv"
    print(f"💾 Сохранение {combined_path}...")
    df_combined.to_csv(combined_path, index=False, encoding="utf-8-sig")
    print(f"   ✅ {len(df_combined):,} строк")

    # ── Статистика ──
    print("\n📊 Статистика:")
    print(f"   RU: {len(df):,}")
    print(f"   KZ: {len(df_kz):,}")
    print(f"   TOTAL: {len(df_combined):,}")

    # Проверка переводов
    for col in ["region", "direction", "status"]:
        ru_vals = df[col].nunique()
        kz_vals = df_kz[col].nunique()
        print(f"   {col}: {ru_vals} ru → {kz_vals} kz уникальных")

    print("\n✅ Готово!")


if __name__ == "__main__":
    main()
